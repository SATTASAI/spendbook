"""Bundle src/ into one dist/worker.js (ES module) that can be pasted into the
Cloudflare dashboard editor or deployed with `wrangler deploy`."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parse = (root / 'src/parse.js').read_text(encoding='utf8')
icons = (root / 'src/icons.js').read_text(encoding='utf8')
worker = (root / 'src/worker.js').read_text(encoding='utf8')
html = (root / 'src/app.html').read_text(encoding='utf8')

parse = re.sub(r'^export ', '', parse, flags=re.M)
icons = re.sub(r'^export ', '', icons, flags=re.M)
worker = re.sub(r"^import .*?;\n", '', worker, flags=re.M)

out = '\n'.join([
    '// สมุดรายจ่าย — Cloudflare Worker (single file, generated by scripts/build.py)',
    '// Needs: D1 binding "DB" -> spendbook-db, secret "APP_KEY".',
    '',
    parse,
    icons,
    'const APP_HTML = ' + json.dumps(html, ensure_ascii=False) + ';',
    '',
    worker,
])
(root / 'dist').mkdir(exist_ok=True)
(root / 'dist/worker.js').write_text(out, encoding='utf8')
print(f'dist/worker.js {len(out.encode()) // 1024} KB')
